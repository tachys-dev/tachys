# `FermionFoundationRBM` has 3.5k (hidden_units=8) and 23k (hidden_units=64)
# parameters -- far too many to read as source literals -- so those two sets
# live in a .npz instead, the same way this suite already stores its other
# large reference arrays.  They are frozen for exactly the same reason.
_NPZ_PATH = Path(__file__).parent / "data" / "frozen_params.npz"
_npz_cache = {}


def _from_npz(name, dtype):
    if not _npz_cache:
        with np.load(_NPZ_PATH) as f:
            _npz_cache.update({k: f[k] for k in f.files})
    prefix = name + "/"
    keys = [k for k in _npz_cache if k.startswith(prefix)]
    if not keys:
        raise KeyError(f"{_NPZ_PATH} holds no parameters named {name!r}")
    tree = {}
    for k in keys:
        node = tree
        *path, leaf = k[len(prefix):].split("/")
        for part in path:
            node = node.setdefault(part, {})
        node[leaf] = jnp.asarray(_npz_cache[k], dtype=dtype)
    return tree


def frozen_params(name, dtype=jnp.float64):
    """Return the frozen parameter tree registered under ``name``.

    A fresh tree is built on every call, so callers may keep or replace leaves
    freely.  ``PARAM_SPECS[name]`` gives the model configuration it goes with.
    """
    if name not in PARAM_SPECS:
        raise KeyError(
            f"no frozen parameters named {name!r}; "
            f"available: {sorted(PARAM_SPECS)}")
    if name in _FROZEN_PARAMS:
        entry = _FROZEN_PARAMS[name]
        return {"params": {layer: {leaf: jnp.asarray(v, dtype=dtype)
                                   for leaf, v in leaves.items()}
                           for layer, leaves in entry.items()}}
    return _from_npz(name, dtype)



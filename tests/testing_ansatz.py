"""Ansatze and frozen parameters used by the test suite.

These are deliberately *not* imported from ``tachys``: the tests pin numerical
regressions (NTK entries, SR/SPRING updates, local energies, sampled
acceptances) that depend on the exact architecture, parameter layout *and*
parameter values of the model, so both must be frozen here rather than tracking
whatever the library happens to define.

For the same reason the parameters below are literals rather than the output of
``model.init(jax.random.key(...))``: JAX's PRNG makes no promise that a given
key yields the same numbers across versions, so an init-derived parameter set
would silently invalidate every hard-coded expected value in the suite. The
literals are the values ``model.init`` produced when they were recorded
(jax 0.7.1 / flax 0.12.0), so the pinned expectations are unchanged.

Changing anything below invalidates those expectations.
"""
from pathlib import Path
from typing import Any

import flax.linen as nn
import jax
import jax.numpy as jnp
import numpy as np


def log_cosh(x):
    """Numerically stable log(cosh(x))."""
    sgn_x = -2 * jnp.signbit(x.real) + 1
    x = x * sgn_x
    return x + jnp.log1p(jnp.exp(-2.0 * x)) - jnp.log(2.0)


class SpinRBM(nn.Module):
    """Restricted Boltzmann machine over ``lattice.spins``.

    Parameter tree: ``linear/{kernel,bias}`` and, when ``complex=True``,
    ``imag_linear/{kernel,bias}``.  Note that ``imag_linear`` is applied to the
    *output* of ``linear``, hence its ``(hidden_units, hidden_units)`` kernel.
    """

    hidden_units: int
    dtype: Any = jnp.float64
    complex: bool = False

    def setup(self):
        self.linear = nn.Dense(
            features=self.hidden_units,
            use_bias=True,
            param_dtype=self.dtype,
        )
        if self.complex:
            self.imag_linear = nn.Dense(
                features=self.hidden_units,
                use_bias=True,
                param_dtype=self.dtype,
            )

    def __call__(self, lattice):
        x = lattice.spins
        x = self.linear(x)
        if self.complex:
            x = x + 1j * self.imag_linear(x)
        x = log_cosh(x.astype(complex))
        return jnp.sum(x, axis=-1)



def _log_det(A):
    """log(det(A)) as a complex number, with a -inf floor on a singular A."""
    sign, logabsdet = jnp.linalg.slogdet(A)
    cdtype = jnp.promote_types(A.dtype, jnp.complex64)
    amp = logabsdet.astype(cdtype) + jnp.log(sign.astype(cdtype))
    return jnp.where(jnp.isnan(amp), -jnp.inf, amp)


class FermionFoundationRBM(nn.Module):
    """Slater determinant with a backflow correction conditioned on couplings.

    Each sample's Hamiltonian couplings (``lattice.system_couplings``) are
    concatenated to the occupations before the backflow network, so one shared
    network can tell which system a sample was drawn from.  The bare orbitals
    stay system-independent.

    Parameter tree: ``orbitals``, ``Dense_0/{kernel,bias}`` (the backflow
    hidden layer) and ``Dense_1/{kernel,bias}`` (its projection back onto
    ``Ne x Ns`` orbitals).
    """

    hidden_units: int

    @nn.compact
    def __call__(self, lattice):
        occupations = jnp.atleast_2d(lattice.occupations)
        Ns = occupations.shape[-1]
        couplings = jnp.atleast_2d(lattice.system_couplings)

        # Bare Slater determinant orbitals, shared across the batch
        orbitals = self.param('orbitals', nn.initializers.xavier_uniform(),
                              (lattice.Ne, Ns,), jnp.float64)

        # Backflow correction, conditioned on the system couplings, one per sample
        backflow_input = jnp.concatenate((occupations, couplings), axis=-1)
        backflow = nn.Dense(self.hidden_units, param_dtype=jnp.float64)(backflow_input)
        backflow = jax.nn.tanh(backflow)
        backflow = nn.Dense(Ns * lattice.Ne, param_dtype=jnp.float64)(backflow)
        backflow = backflow.reshape(occupations.shape[0], lattice.Ne, Ns)
        orbitals = orbitals[None] + backflow

        # Positions of the occupied sites, per sample
        R = jax.vmap(lambda o: o.nonzero(size=lattice.Ne)[0])(occupations)
        A = jnp.take_along_axis(orbitals, R[:, None, :], axis=2)
        return _log_det(A)

